"""Verifica los días calculados en el CSV de planificación 2026."""
from datetime import datetime

def parse_date(s):
    s = s.strip()
    if not s:
        return None
    parts = s.split('/')
    d, m, y = int(parts[0]), int(parts[1]), int(parts[2])
    return datetime(y, m, d)

def dias(ini, fin):
    if not ini or not fin:
        return 0
    return (fin - ini).days

